#!/usr/bin/env node
// 把主应用生成的 domain 模块清单同步进 lab。
//
// 背景：plot 只为 `web` artifact 生成 modules.gen.ts，`web.lab` 拿到的是空列表。
// lab 需要同一批 domain 才能和正式版对齐，所以维护一份自己的清单。
//
// 用法：node app/src/web.lab/scripts/sync-modules.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '../../../..')
const source = resolve(repoRoot, 'app/src/web/src/generated/modules.gen.ts')
const target = resolve(repoRoot, 'app/src/web.lab/src/lab-modules.ts')

const header = [
  '// lab 自有模块清单：从 app/src/web/src/generated/modules.gen.ts 同步。',
  '// 同步命令：node app/src/web.lab/scripts/sync-modules.mjs',
  '// 不要手改——main 新增 domain 时跑一次同步即可。',
  '',
  '',
].join('\n')

const generated = readFileSync(source, 'utf8')
const body = generated.replace(/^\/\/ Generated by Plot\. DO NOT EDIT\.\n/, '').replace(/^\n+/, '')

const next = `${header}${body}`
const current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n')

if (current === next) {
  console.log('lab-modules.ts 已是最新，无需同步。')
  process.exit(0)
}

writeFileSync(target, next)
const count = (next.match(/^  \w+WebModule,$/gm) ?? []).length
console.log(`lab-modules.ts 已同步，共 ${count} 个 domain 模块。`)
console.log('提示：同步后跑一次 pnpm typecheck，确认新增 domain 的依赖已在 package.json 中。')
